const replaceTextNodes = (dictionary) => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script, style, svg')) return NodeFilter.FILTER_REJECT;
      return dictionary[node.nodeValue.trim()] ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const value = node.nodeValue.trim();
    node.nodeValue = node.nodeValue.replace(value, dictionary[value]);
  });
};

const replaceAttributes = (dictionary) => {
  document.querySelectorAll('[aria-label]').forEach((element) => {
    const value = element.getAttribute('aria-label');
    if (dictionary[value]) element.setAttribute('aria-label', dictionary[value]);
  });
};

const applyLanguage = (language) => {
  const toEnglish = language === 'en';
  replaceTextNodes(toEnglish ? translations : reverseTranslations);
  replaceAttributes(toEnglish ? translatedAttributes : reverseAttributes);
  document.documentElement.lang = language;
  document.title = toEnglish ? 'Maxim Tarasyuk — Sales, CRM & Marketing Analyst' : 'Максим Тарасюк — аналитик по продажам, CRM и маркетингу';
  document.querySelector('meta[name="description"]')?.setAttribute('content', toEnglish
    ? 'Sales funnel, CRM, acquisition channel and business process analysis for B2C companies.'
    : 'Бизнес-анализ воронки продаж, CRM, рекламных источников и процессов для B2C-компаний.');
  document.querySelectorAll('[data-language-toggle]').forEach((button) => {
    button.textContent = toEnglish ? 'RU' : 'EN';
    button.setAttribute('aria-label', toEnglish ? 'Переключить на русский' : 'Switch to English');
    button.setAttribute('title', toEnglish ? 'Переключить на русский' : 'Switch to English');
  });
  try { localStorage.setItem('portfolio-language', language); } catch {}
};

let currentLanguage = 'ru';
